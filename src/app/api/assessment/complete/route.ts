import { z } from "zod";
import { AIError } from "@/lib/ai/client";
import { isAssessmentComplete, scoreAssessment } from "@/lib/domain/assessment";
import { DIMENSIONS, type Dimension } from "@/lib/domain/dimensions";
import { apiRoute, dbError, HttpError } from "@/lib/server/api";
import { generateDevelopmentProfile } from "@/lib/server/profile";
import { awardAchievements } from "@/lib/server/progress";

export const maxDuration = 120;

const schema = z.object({
  held_back: z.string().trim().min(10, "Please describe a situation in a sentence or two.").max(2000),
  goal: z.string().trim().min(10, "Please describe your goal in a sentence or two.").max(2000),
});

export const POST = apiRoute(schema, async (reflections, { supabase, user, state }) => {
  const { data: assessment } = await supabase
    .from("assessments")
    .select("id")
    .eq("user_id", user.id)
    .eq("status", "in_progress")
    .order("started_at", { ascending: false })
    .limit(1)
    .maybeSingle();
  if (!assessment) throw new HttpError(409, "No assessment in progress.");

  const { data: responses } = await supabase
    .from("assessment_responses")
    .select("question_id, value")
    .eq("assessment_id", assessment.id);
  const answers = responses ?? [];
  if (!isAssessmentComplete(answers)) throw new HttpError(400, "Please answer every question before finishing.");

  const raw = scoreAssessment(answers);
  const scores = Object.fromEntries(DIMENSIONS.map((d) => [d, raw[d] ?? 0])) as Record<Dimension, number>;
  const isFirstBaseline = state.skills.length === 0;

  const { error } = await supabase
    .from("assessments")
    .update({ status: "completed", scores, reflections, completed_at: new Date().toISOString() })
    .eq("id", assessment.id);
  dbError(error);

  if (isFirstBaseline) {
    const upsert = await supabase.from("skill_progress").upsert(
      DIMENSIONS.map((d) => ({
        user_id: user.id,
        dimension: d,
        baseline: scores[d],
        current: scores[d],
        self_reported: scores[d],
        evidence_count: 0,
        explanation: `Baseline from your initial assessment: ${scores[d]}.`,
      })),
    );
    dbError(upsert.error);
    const hist = await supabase.from("personality_scores").insert(
      DIMENSIONS.map((d) => ({ user_id: user.id, dimension: d, score: scores[d], self_reported: scores[d], source: "baseline", explanation: "Initial assessment" })),
    );
    dbError(hist.error);
  }
  if (!state.profile.programme_start_date) {
    const p = await supabase.from("profiles").update({ programme_start_date: state.today }).eq("id", user.id);
    dbError(p.error);
  }
  await awardAchievements(supabase, user.id);

  // The profile is generated by AI; scores are already saved if generation fails.
  try {
    const profile = await generateDevelopmentProfile(supabase, user.id, scores, reflections);
    return { scores, profile };
  } catch (err) {
    if (err instanceof AIError) return { scores, profile: null, profileError: err.message };
    throw err;
  }
});
